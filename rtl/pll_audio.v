    // Simplified PLL simulation model using counter
    // This is NOT synthesizable for actual hardware - use ALTPLL IP
    reg [5:0] counter;
    reg clk_out;
    reg pll_locked;
    
    always @(posedge inclk0 or posedge areset) begin
        if (areset) begin
            counter <= 6'd0;
            clk_out <= 1'b0;
            pll_locked <= 1'b0;
        end else begin
            // Divide 50 MHz by approximately 4 to get ~12.5 MHz (close to 12.288)
            // Actual ratio: 50 / 12.288 = 4.069
            // Toggle every 2 cycles: 50MHz / 4 = 12.5 MHz
            if (counter >= 6'd1) begin  // Count 0,1 then toggle (divide by 4 total)
                counter <= 6'd0;
                clk_out <= ~clk_out;
            end else begin
                counter <= counter + 1;
            end
            pll_locked <= 1'b1;
        end
    end
    
    assign c0 = clk_out;
    assign locked = pll_locked;
    
